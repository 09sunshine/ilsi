function lesson(
  moduleId: string,
  order: number,
  type: Lesson["type"],
  titleEn: string,
  titleFr: string,
  bodyEn: string,
  bodyFr: string,
  minutes: number,
  mandatory = true,
  resources: Resource[] = [],
): Lesson {
  return {
    id: `${moduleId}-l${order}`,
    moduleId,
    order,
    type,
    title: b(titleEn, titleFr),
    description: b(
      `${type === "VIDEO" ? "Video" : type === "CASE_STUDY" ? "Case study" : "Lesson"} · ${minutes} min`,
      `${type === "VIDEO" ? "Vidéo" : type === "CASE_STUDY" ? "Étude de cas" : "Leçon"} · ${minutes} min`,
    ),
    body: b(bodyEn, bodyFr),
    videoUrl: type === "VIDEO" ? "https://www.w3schools.com/html/mov_bbb.mp4" : undefined,
    durationMinutes: minutes,
    mandatory,
    resources,
  };
}

